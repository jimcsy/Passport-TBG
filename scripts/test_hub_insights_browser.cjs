require('tsx/cjs');
const assert = require('node:assert/strict');
const { prisma } = require('../lib/db/prisma.ts');
const { SignJWT } = require('jose');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.HUB_TEST_ORIGIN || 'http://localhost:3100';
const prefix = `HUBUI-${Date.now()}`;
let trainer, trainee, plan, browser, stage = 'fixtures';
(async () => {
  trainer = await prisma.adminUser.create({ data: { employeeId: prefix, fullName: 'Hub insights fixture trainer', email: `${prefix}@example.invalid`, passwordHash: 'unused' } });
  trainee = await prisma.trainee.create({ data: { traineeCode: prefix, fullName: 'Hub insights fixture trainee', email: `${prefix}@example.invalid`, restaurantBrand: 'Insights fixture brand', branchLocation: 'Test', cohortBatch: 'Insights fixture cohort', hireDate: new Date() } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Hub fixture plan', roleIdentifier: prefix, status: 'PUBLISHED', createdById: trainer.id } });
  const version = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, status: 'PUBLISHED', publishedById: trainer.id } });
  const node = await prisma.planNode.create({ data: { planVersionId: version.id, code: prefix, title: 'Hub insights module fixture', description: 'Open this module to record a first content view.', path: 'ONBOARDING', orderIndex: 1, posX: 0, posY: 0 } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: version.id, assignedById: trainer.id } });
  browser = await chromium.launch({ headless: true });
  const token = payload => new SignJWT(payload).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  const staff = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await staff.addCookies([{ name: 'beat_admin_session', value: await token({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }), url: origin }]);
  const page = await staff.newPage(); page.setDefaultTimeout(60000); page.setDefaultNavigationTimeout(60000);
  const errors = []; page.on('pageerror', error => errors.push(error.name));
  stage = 'first actual module opening';
  const learner = await browser.newContext();
  await learner.addCookies([{ name: 'beat_trainee_session', value: await token({ id: trainee.id, traineeCode: trainee.traineeCode, fullName: trainee.fullName, portal: 'trainee' }), url: origin }]);
  const student = await learner.newPage(); student.setDefaultTimeout(60000); student.setDefaultNavigationTimeout(60000);
  await student.goto(`${origin}/trainee/dashboard`, { waitUntil: 'networkidle' });
  assert.equal(await prisma.traineeContentView.count({ where: { traineeId: trainee.id } }), 0, 'Dashboard/prefetch must not count as a module view');
  await student.goto(`${origin}/trainee/dashboard/modules/${node.id}`, { waitUntil: 'networkidle' });
  await student.getByRole('heading', { name: 'Module details', exact: true }).waitFor();
  let first;
  for (let i = 0; i < 60; i++) { first = await prisma.traineeContentView.findUnique({ where: { traineeId: trainee.id } }); if (first) break; await student.waitForTimeout(500); }
  assert.ok(first, 'Visible module opening is recorded');
  await student.reload({ waitUntil: 'networkidle' });
  assert.deepEqual(await prisma.traineeContentView.findUniqueOrThrow({ where: { traineeId: trainee.id } }), first);
  console.log('PASS: dashboard does not record a view; actual module render records it; reload preserves one first-view record');
  stage = 'Hub data and chart';
  await page.goto(`${origin}/trainer`, { waitUntil: 'networkidle' });
  const cards = page.getByRole('navigation', { name: 'Trainer insights and tools', exact: true });
  const viewers = await prisma.traineeContentView.count();
  assert.equal(await cards.getByRole('region', { name: 'Training Content', exact: true }).locator('p').first().textContent(), viewers.toLocaleString('en-PH'));
  assert.equal(await cards.getByRole('link', { name: 'Trainee directory', exact: true }).getAttribute('href'), '/trainer/trainees');
  assert.equal(await cards.getByRole('link', { name: 'Explore training content', exact: true }).getAttribute('href'), '/trainer/plans');
  assert.equal(await cards.getByRole('link', { name: 'Open verifications', exact: true }).getAttribute('href'), '/trainer/queue');
  await page.getByRole('heading', { name: 'Cohort progress', exact: true }).waitFor();
  const chart = page.getByRole('region', { name: 'Trainee engagement', exact: true });
  await chart.getByRole('button', { name: '7 days', exact: true }).click();
  assert.equal(await chart.getByRole('button', { name: '7 days', exact: true }).getAttribute('aria-pressed'), 'true');
  await chart.getByRole('img', { name: /last 7 days/ }).waitFor();
  const explorer = chart.getByRole('group', { name: /^Engagement trend/ });
  await explorer.focus(); const before = await chart.locator('[aria-live=polite]').textContent();
  await page.keyboard.press('ArrowLeft'); assert.notEqual(await chart.locator('[aria-live=polite]').textContent(), before);
  await chart.getByRole('button', { name: '30 days', exact: true }).click();
  stage = 'responsive placement';
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `No overflow at ${width}`);
    const bounds = await chart.boundingBox(), insights = await page.getByRole('complementary', { name: 'Training insights', exact: true }).boundingBox();
    if (width >= 1024) assert.ok(insights.x >= bounds.x + bounds.width, 'Insights are to the right of the graph');
    for (const link of await cards.getByRole('link').all()) assert.ok((await link.boundingBox()).height >= 44);
    await page.screenshot({ path: `/tmp/hub-insights-${width}.png`, fullPage: true });
  }
  assert.deepEqual(errors, []);
  console.log('PASS: correct CTA destinations, retained cohorts, date-range/keyboard chart interaction and responsive cards/graph/right-side insights at 320–1440px');
})().catch(error => { console.error(`Hub browser check failed at ${stage}: ${String(error.message).replace(/(?:postgres(?:ql)?|https?):\/\/\S+/g, '[URL]').slice(0, 1800)}`); process.exitCode = 1; }).finally(async () => {
  await browser?.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
