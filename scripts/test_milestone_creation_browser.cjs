// PLAYWRIGHT_MODULE=/tmp/passport-revoke-browser/node_modules/playwright node --env-file=.env scripts/test_milestone_creation_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
require('tsx/cjs');
const assert = require('node:assert/strict');
const { prisma } = require('../lib/db/prisma.ts');
const { SignJWT } = require('jose');
const { verificationData } = require('../lib/stamps/hash.ts');
const origin = process.env.CREATION_TEST_ORIGIN || 'http://localhost:3100';
const prefix = `TC1B-${String(Date.now()).slice(-8)}`;
let trainer, trainee, plan, browser, stage = 'fixtures';
(async () => {
  trainer = await prisma.adminUser.create({ data: { employeeId: prefix, fullName: 'Creation Fixture Trainer', email: `${prefix}@example.invalid`, role: 'TRAINER', passwordHash: 'unused-fixture' } });
  trainee = await prisma.trainee.create({ data: { traineeCode: prefix, fullName: 'Creation Fixture Trainee', email: `${prefix}-trainee@example.invalid`, restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  const standard = await prisma.milestoneDefinition.create({ data: { code: `${prefix}-STD`, title: 'Protected canonical fixture', description: 'This canonical content must never be overwritten through creation.', path: 'TECHNICAL', isStandard: true } });
  const baseline = await prisma.milestoneDefinition.create({ data: { code: `${prefix}-LIVE`, title: 'Active verified fixture', description: 'Existing trainee approval must remain untouched by content creation.', path: 'ONBOARDING', isStandard: false } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Safe creation browser fixture', roleIdentifier: 'TC01', status: 'PUBLISHED', createdById: trainer.id } });
  const live = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, publishedById: trainer.id, status: 'PUBLISHED' } });
  const draft = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 2, publishedById: trainer.id, status: 'DRAFT' } });
  const nodeData = { libraryMilestoneId: baseline.id, code: baseline.code, title: baseline.title, description: baseline.description, path: baseline.path, orderIndex: 1, posX: 0, posY: 0, isCustom: false };
  const liveNode = await prisma.planNode.create({ data: { ...nodeData, planVersionId: live.id } });
  await prisma.planNode.create({ data: { ...nodeData, planVersionId: draft.id } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: live.id, assignedById: trainer.id } });
  const originalProgress = await prisma.traineeProgress.create({ data: { traineeId: trainee.id, planNodeId: liveNode.id, ...verificationData(trainee.id, liveNode.id, trainer.id, new Date(), 'Keep original stamp') } });
  const token = await new SignJWT({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: trainer.role, portal: 'trainer' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: 'beat_admin_session', value: token, url: origin }]);
  const page = await context.newPage(); page.setDefaultTimeout(20000);
  const errors = []; page.on('pageerror', error => errors.push(error.name));
  const builderUrl = `${origin}/trainer/plans/${plan.id}/builder`;
  await page.goto(builderUrl, { waitUntil: 'networkidle' });
  await page.getByRole('navigation', { name: 'Focus development path' }).getByRole('button', { name: /^Technical Skills/ }).click();
  await page.waitForTimeout(550);
  await page.locator('.react-flow__node[data-id="root-TECHNICAL"]').getByRole('button', { name: 'Add milestone', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Create milestone', exact: true });
  const title = 'Creation details retained on failure';
  const description = 'Demonstrate the custom fixture competency before requesting verification.';
  await dialog.locator('#milestoneCode').fill(standard.code);
  await dialog.locator('#milestoneTitle').fill(title);
  await dialog.locator('#milestoneDesc').fill(description);
  stage = 'canonical conflict and retained fields';
  await dialog.getByRole('button', { name: 'Add to Canvas', exact: true }).click();
  await dialog.getByText('This code already exists in the shared library. Choose another code or add the existing milestone.', { exact: true }).waitFor();
  assert.ok(await dialog.isVisible());
  assert.equal(await dialog.locator('#milestoneCode').inputValue(), standard.code);
  assert.equal(await dialog.locator('#milestoneTitle').inputValue(), title);
  assert.equal(await dialog.locator('#milestoneDesc').inputValue(), description);
  assert.equal(await page.locator('.react-flow__node-milestone').count(), 1);
  assert.deepEqual(await prisma.milestoneDefinition.findUniqueOrThrow({ where: { id: standard.id } }), standard);
  assert.equal(await page.getByRole('status').filter({ hasText: /added to/ }).count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/tc01-create-conflict-mobile.png', fullPage: false });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  console.log('PASS: canonical conflict leaves form fields, canvas, saved definition and success state unchanged on desktop/mobile');

  stage = 'transport failure';
  const newCode = `${prefix}-NEW`;
  await dialog.locator('#milestoneCode').fill(newCode);
  let block = true, hold = false, release;
  await page.route('**/*', async route => {
    const request = route.request();
    if (request.method() === 'POST' && (request.postData() || '').includes(newCode)) {
      if (block) { block = false; await route.abort(); return; }
      if (hold) await new Promise(resolve => { release = resolve; });
    }
    await route.continue();
  });
  await dialog.getByRole('button', { name: 'Add to Canvas', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(await dialog.locator('#milestoneCode').inputValue(), newCode);
  assert.equal(await dialog.locator('#milestoneTitle').inputValue(), title);
  assert.equal(await prisma.milestoneDefinition.count({ where: { code: newCode } }), 0);
  assert.equal(await prisma.planNode.count({ where: { planVersionId: draft.id } }), 1);
  console.log('PASS: network failure retains entered details without creating a library item, draft node or success message');

  stage = 'pending and real ID handoff';
  hold = true;
  await dialog.getByRole('button', { name: 'Add to Canvas', exact: true }).click();
  await dialog.getByRole('button', { name: 'Adding…', exact: true }).waitFor();
  assert.equal(await dialog.getByRole('button', { name: 'Cancel', exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByRole('button', { name: 'Close milestone creation', exact: true }).isDisabled(), true);
  assert.equal(await dialog.locator('#milestoneCode').isDisabled(), true);
  assert.equal(await page.locator('.react-flow__node-milestone').count(), 0); // Mobile outline has no canvas.
  const overlay = page.locator('.portal-modal-overlay').filter({ has: dialog });
  await overlay.click({ position: { x: 2, y: 2 } });
  assert.equal(await dialog.isVisible(), true);
  for (let i = 0; i < 30 && !release; i++) await page.waitForTimeout(50);
  assert.ok(release); release(); hold = false;
  await dialog.waitFor({ state: 'detached', timeout: 45000 });
  const saved = await prisma.milestoneDefinition.findUniqueOrThrow({ where: { code: newCode } });
  assert.equal(saved.isStandard, false); assert.equal(saved.id.startsWith('custom-def-'), false);
  await page.getByRole('combobox', { name: 'Development path', exact: true }).selectOption('TECHNICAL');
  await page.getByRole('button', { name: `Inspect ${newCode}`, exact: true }).click();
  const inspector = page.getByRole('dialog', { name: 'Milestone inspector', exact: true });
  await inspector.getByRole('region', { name: 'Course materials', exact: true }).getByText('No materials attached yet.', { exact: true }).waitFor();
  assert.equal(await inspector.getByLabel(`Attach materials to ${newCode}`, { exact: true }).isVisible(), true);
  assert.equal(await inspector.getByText('Save the draft and reload it before attaching materials to a new custom milestone.', { exact: true }).count(), 0);
  await inspector.getByRole('button', { name: 'Close inspector', exact: true }).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Draft saved.', { exact: true }).waitFor({ timeout: 45000 });
  const savedNode = await prisma.planNode.findFirstOrThrow({ where: { planVersionId: draft.id, code: newCode } });
  assert.equal(savedNode.libraryMilestoneId, saved.id);
  console.log('PASS: pending creation cannot be dismissed; successful retry returns a persisted ID usable by materials immediately and retained on explicit draft save');

  stage = 'plan-only creation and preservation';
  await page.getByRole('button', { name: 'Add Milestone', exact: true }).click();
  const privateCode = `${prefix}-LOCAL`;
  await dialog.locator('#milestoneCode').fill(privateCode);
  await dialog.locator('#milestoneTitle').fill('Plan-only fixture milestone');
  await dialog.locator('#milestoneDesc').fill(description);
  await dialog.getByRole('checkbox').uncheck();
  await dialog.getByRole('button', { name: 'Add to Canvas', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await prisma.milestoneDefinition.count({ where: { code: privateCode } }), 0);
  await page.getByText(`Custom milestone "${privateCode}" added to this draft.`, { exact: true }).waitFor();
  assert.equal(await prisma.planNode.count({ where: { planVersionId: live.id } }), 1);
  assert.equal(await prisma.planVersion.count({ where: { planId: plan.id, status: 'PUBLISHED' } }), 1);
  assert.deepEqual(await prisma.traineeProgress.findUniqueOrThrow({ where: { id: originalProgress.id } }), originalProgress);
  assert.equal((await prisma.traineePlanAssignment.findFirstOrThrow({ where: { traineeId: trainee.id, status: 'ACTIVE' } })).planVersionId, live.id);
  assert.deepEqual(errors, []);
  console.log('PASS: plan-only creation avoids the library and reports accurate scope; published curriculum, trainee assignment and original stamp remain unchanged');
})().catch(error => { console.error(`Milestone creation browser check failed at ${stage}: ${String(error.message || error.name).replace(/(?:postgres(?:ql)?|https?):\/\/\S+/g, '[URL]').slice(0, 1700)}`); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  await prisma.milestoneDefinition.deleteMany({ where: { code: { startsWith: prefix } } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
