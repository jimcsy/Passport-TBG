// PLAYWRIGHT_BROWSERS_PATH=/tmp/passport-registration-browser/browsers PLAYWRIGHT_MODULE=/tmp/passport-registration-browser/node_modules/playwright node --env-file=.env scripts/test_review_notifications_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
require('tsx/cjs');
const { prisma } = require('../lib/db/prisma.ts');
const { STROBI_MASCOT_MAP } = require('../lib/constants/mascots.ts');
const { verifyAssignedMilestones } = require('../lib/db/repositories/verification.ts');
const { SignJWT } = require('jose');
const assert = require('node:assert/strict');
const origin = process.env.STROBI_TEST_ORIGIN || 'http://localhost:3100';
let browser, trainer, secondTrainer, trainee, plan;
(async () => {
  const suffix = String(Date.now());
  trainer = await prisma.adminUser.create({ data: { employeeId: `STROBI-${suffix}`, email: `strobi-${suffix}@example.invalid`, fullName: 'Strobi Test Trainer', passwordHash: 'unused-test-password' } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Strobi browser fixture', roleIdentifier: 'STROBI_TEST', status: 'PUBLISHED', createdById: trainer.id } });
  const version = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, status: 'PUBLISHED', publishedById: trainer.id } });
  const nodes = [];
  for (const [path, mascot] of Object.entries(STROBI_MASCOT_MAP)) {
    nodes.push(await prisma.planNode.create({ data: { planVersionId: version.id, path, code: `STROBI-${suffix}-${path}`, title: `${mascot.category} celebration test`, description: 'Isolated Strobi browser check', orderIndex: 1, posX: 0, posY: 0 } }));
  }
  trainee = await prisma.trainee.create({ data: { traineeCode: `STROBI-${suffix}`, fullName: 'Strobi Test Trainee', email: `strobit-${suffix}@example.invalid`, restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: version.id, assignedById: trainer.id } });
  await prisma.traineeProgress.createMany({ data: nodes.map(node => ({ traineeId: trainee.id, planNodeId: node.id, status: node.path === 'ONBOARDING' ? 'READY_FOR_REVIEW' : 'IN_PROGRESS', traineeNote: node.path === 'ONBOARDING' ? 'Submitted while trainer was away' : null, requestedAt: node.path === 'ONBOARDING' ? new Date() : null })) });
  browser = await chromium.launch({ headless: true });
  async function context(payload, name) {
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    const token = await new SignJWT(payload).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
    await ctx.addCookies([{ name, value: token, url: origin }]);
    return ctx;
  }
  const learner = await context({ id: trainee.id, traineeCode: trainee.traineeCode, fullName: trainee.fullName, email: trainee.email, portal: 'trainee' }, 'beat_trainee_session');
  secondTrainer = await prisma.adminUser.create({ data: { employeeId: `SECOND-${suffix}`, email: `second-${suffix}@example.invalid`, fullName: 'Second Review Trainer', passwordHash: 'unused-test-password' } });
  const payload = admin => ({ id: admin.id, employeeId: admin.employeeId, fullName: admin.fullName, role: 'TRAINER', portal: 'trainer' });
  const staff = await context(payload(trainer), 'beat_admin_session');
  const page = await staff.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install();
  await page.goto(origin + '/trainer', { waitUntil: 'networkidle' });
  const bell = page.getByRole('button', { name: /^Review notifications/ });
  await bell.click();
  const panel = page.getByRole('region', { name: 'Review notifications', exact: true });
  const firstLabel = 'Strobi Test Trainee — Onboarding celebration test';
  await panel.getByRole('button', { name: 'Unread: ' + firstLabel, exact: true }).click();
  await page.waitForURL(/review=/);
  const first = await prisma.traineeProgress.findUniqueOrThrow({ where: { traineeId_planNodeId: { traineeId: trainee.id, planNodeId: nodes[0].id } } });
  const card = page.locator('#review-' + first.id);
  await card.getByText('Submitted while trainer was away', { exact: false }).waitFor();
  assert.equal(await card.getByRole('button', { name: new RegExp(nodes[0].code + ':') }).getAttribute('aria-expanded'), 'true');
  assert.equal(await card.evaluate(element => element === document.activeElement), true);
  await page.reload({ waitUntil: 'networkidle' });
  await bell.click();
  await panel.getByRole('button', { name: 'Read: ' + firstLabel, exact: true }).waitFor();
  assert((await panel.boundingBox()).width <= 320);
  await page.keyboard.press('Escape');
  await panel.waitFor({ state: 'detached' });
  console.log('PASS: requests submitted while away appear, notification opens/expands/focuses exact queue card, read state persists across reload, compact panel');
  const otherStaff = await context(payload(secondTrainer), 'beat_admin_session');
  const otherPage = await otherStaff.newPage();
  await otherPage.goto(origin + '/trainer', { waitUntil: 'networkidle' });
  await otherPage.getByRole('button', { name: /^Review notifications/ }).click();
  await otherPage.getByRole('button', { name: 'Unread: ' + firstLabel, exact: true }).waitFor();
  assert.equal(await prisma.reviewNotificationRead.count({ where: { trainerId: secondTrainer.id } }), 0);
  await otherStaff.close();
  await page.goto(origin + '/trainer/queue?tab=batch', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Cohort Batch Sign-Off/ }).waitFor();
  const traineePage = await learner.newPage();
  await traineePage.goto(origin + '/trainee/dashboard/modules/' + nodes[1].id, { waitUntil: 'networkidle' });
  await traineePage.getByLabel('Add a reflection for your trainer (optional)', { exact: true }).fill('New communication reflection submitted in browser');
  await traineePage.getByRole('button', { name: 'Submit for review', exact: true }).click();
  await traineePage.getByRole('button', { name: 'Awaiting trainer review', exact: true }).waitFor();
  await page.bringToFront();
  await page.clock.fastForward(30001);
  await bell.click();
  const secondLabel = 'Strobi Test Trainee — Communication Skills celebration test';
  await panel.getByRole('button', { name: 'Unread: ' + secondLabel, exact: true }).waitFor({ timeout: 45000 });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileBox = await panel.boundingBox();
  assert(mobileBox.x >= 0 && mobileBox.x + mobileBox.width <= 390);
  await panel.getByRole('button', { name: 'Unread: ' + secondLabel, exact: true }).click();
  const second = await prisma.traineeProgress.findUniqueOrThrow({ where: { traineeId_planNodeId: { traineeId: trainee.id, planNodeId: nodes[1].id } } });
  const secondCard = page.locator('#review-' + second.id);
  await secondCard.getByText('New communication reflection submitted in browser', { exact: false }).waitFor();
  await secondCard.getByRole('button', { name: '1-Click Verify & Stamp', exact: true }).click();
  await page.getByText('Stamped & Verified!', { exact: true }).waitFor();
  await page.clock.fastForward(30001);
  await bell.click();
  await panel.getByRole('button', { name: 'Read: ' + firstLabel, exact: true }).waitFor();
  await panel.getByRole('button', { name: new RegExp('Communication Skills celebration test') }).waitFor({ state: 'detached', timeout: 45000 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: per-trainer unread state, real trainee submission → polling → notification, batch tab switches to exact request, mobile layout, approved requests leave notifications, no browser errors');
})().catch(error => { console.error(error.stack); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  if (secondTrainer) await prisma.adminUser.delete({ where: { id: secondTrainer.id } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
