// PLAYWRIGHT_MODULE=/tmp/passport-mobile-browser/node_modules/playwright node --env-file=.env scripts/test_builder_workspace_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
require('tsx/cjs');
const assert = require('node:assert/strict');
const { prisma } = require('../lib/db/prisma.ts');
const { SignJWT } = require('jose');
const { verificationData } = require('../lib/stamps/hash.ts');
const origin = process.env.BUILDER_TEST_ORIGIN || 'http://localhost:3100';
const suffix = String(Date.now()).slice(-8);
let browser, trainer, trainee, plan, definitions = [], stage = 'fixtures';
(async () => {
  trainer = await prisma.adminUser.create({ data: { employeeId: `BW-${suffix}`, email: `bw-${suffix}@example.invalid`, fullName: 'Builder Workspace Trainer', role: 'TRAINER', passwordHash: 'unused-fixture' } });
  trainee = await prisma.trainee.create({ data: { traineeCode: `BW-${suffix}`, fullName: 'Builder Workspace Trainee', email: `bwt-${suffix}@example.invalid`, restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Builder workspace with a long curriculum title for responsive verification', roleIdentifier: 'BUILDER_WORKSPACE', status: 'PUBLISHED', createdById: trainer.id } });
  const published = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, publishedById: trainer.id } });
  for (const [index, path] of ['ONBOARDING', 'ONBOARDING', 'TECHNICAL', 'TECHNICAL'].entries()) definitions.push(await prisma.milestoneDefinition.create({ data: { code: `BW-${suffix}-${index}`, title: `Workspace milestone ${index}`, description: 'Demonstrate the fixture curriculum skills and verification criteria.', path, orderIndex: index === 1 ? 2 : 1, isStandard: false } }));
  await prisma.planNode.createMany({ data: definitions.slice(0, 3).map((item, index) => ({ planVersionId: published.id, libraryMilestoneId: item.id, code: item.code, title: item.title, description: item.description, path: item.path, orderIndex: item.orderIndex, posX: 0, posY: 0, isCustom: index > 0 })) });
  const originals = await prisma.planNode.findMany({ where: { planVersionId: published.id } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: published.id, assignedById: trainer.id } });
  const stamped = await prisma.traineeProgress.create({ data: { traineeId: trainee.id, planNodeId: originals.find(node => node.code === definitions[0].code).id, ...verificationData(trainee.id, originals.find(node => node.code === definitions[0].code).id, trainer.id, new Date(), 'Original workspace fixture stamp') } });
  const token = await new SignJWT({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: 'beat_admin_session', value: token, url: origin }]);
  const page = await context.newPage(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', error => errors.push(error.name));
  const canvas = page.locator('.react-flow');
  const node = code => page.locator('.react-flow__node-milestone').filter({ has: page.getByText(code, { exact: true }) });
  const inspector = () => page.locator('#builder-inspector');
  const versions = () => page.locator('summary').filter({ hasText: 'Versions' });
  const dismissNotice = async () => { const close = page.getByRole('button', { name: 'Dismiss notification', exact: true }); if (await close.isVisible()) await close.click(); };
  const settle = () => page.waitForTimeout(550);
  async function noOverflow(label) { assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, label); }

  stage = 'canvas space and navigation';
  await page.goto(`${origin}/trainer/plans/${plan.id}/builder`, { waitUntil: 'networkidle' }); await settle();
  assert.equal(await inspector().isVisible(), false);
  const originalWidth = (await canvas.boundingBox()).width;
  assert.ok(originalWidth > 1000, `expected canvas >1000px, got ${originalWidth}`);
  await page.getByRole('button', { name: 'Collapse path navigation', exact: true }).click();
  assert.ok((await canvas.boundingBox()).width > originalWidth + 180);
  await page.getByRole('button', { name: 'Paths', exact: true }).click();
  await page.getByRole('navigation', { name: 'Focus development path' }).getByRole('button', { name: /^Onboarding/ }).click(); await settle();
  await node(definitions[0].code).click();
  await page.getByRole('complementary', { name: 'Milestone inspector', exact: true }).waitFor();
  const dockedCanvas = await canvas.boundingBox(), dockedPanel = await inspector().boundingBox();
  assert.ok(dockedCanvas.x + dockedCanvas.width <= dockedPanel.x + 1, 'inspector must dock beside the canvas');
  assert.equal(await inspector().getByRole('button', { name: 'Save changes', exact: true }).count(), 0);
  assert.equal(await inspector().locator('#editMilestoneTitle').isDisabled(), true);
  await inspector().getByRole('button', { name: 'Close inspector', exact: true }).click();
  console.log('PASS: full-width canvas, collapsible path rail, contextual published inspection and read-only restrictions');

  stage = 'draft inspector validation and editing';
  await page.setViewportSize({ width: 390, height: 844 }); await settle();
  await page.getByRole('button', { name: `Inspect ${definitions[0].code}`, exact: true }).click();
  const previewFile = await prisma.courseMaterial.create({ data: { milestoneId: definitions[0].id, fileName: 'workspace-preview.pdf', mimeType: 'application/pdf', fileType: 'PDF', fileSizeBytes: 12, storagePath: `workspace-no-object/${definitions[0].id}/preview.pdf`, uploadedById: trainer.id } });
  await inspector().getByRole('button', { name: 'Close inspector', exact: true }).click();
  await page.getByRole('button', { name: `Inspect ${definitions[0].code}`, exact: true }).click();
  await inspector().getByRole('button', { name: 'Preview / download', exact: true }).click();
  await page.getByRole('dialog', { name: 'workspace-preview.pdf', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog', { name: 'workspace-preview.pdf', exact: true }).count(), 0);
  assert.equal(await inspector().isVisible(), true, 'Escape closes the material preview without closing the inspector');
  await inspector().getByRole('button', { name: 'Close inspector', exact: true }).click();
  await prisma.courseMaterial.delete({ where: { id: previewFile.id } });
  await page.setViewportSize({ width: 1440, height: 1000 }); await settle();
  await page.getByRole('button', { name: 'New draft', exact: true }).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).waitFor({ timeout: 45000 }); await dismissNotice();
  await node(definitions[1].code).click();
  await inspector().locator('#editMilestoneTitle').fill('Workspace draft title');
  await page.getByRole('button', { name: 'Outline view', exact: true }).click();
  await page.getByRole('button', { name: `Inspect ${definitions[0].code}`, exact: true }).click();
  await page.getByRole('button', { name: `Inspect ${definitions[1].code}`, exact: true }).click();
  assert.equal(await inspector().locator('#editMilestoneTitle').inputValue(), 'Workspace draft title', 'staged edits survive contextual selection');
  await inspector().locator('#editMilestoneCode').fill(definitions[0].code);
  await inspector().getByRole('button', { name: 'Save changes', exact: true }).click();
  await inspector().getByText(`Milestone code "${definitions[0].code}" already exists.`, { exact: true }).waitFor();
  await inspector().locator('#editMilestoneCode').fill(definitions[1].code);
  await inspector().getByRole('button', { name: 'Save changes', exact: true }).click();
  await inspector().waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Canvas view', exact: true }).click(); await settle();
  await node(definitions[1].code).getByText('Workspace draft title', { exact: true }).waitFor();
  assert.equal((await prisma.milestoneDefinition.findUniqueOrThrow({ where: { id: definitions[1].id } })).title, definitions[1].title);
  await node(definitions[0].code).click();
  assert.equal(await inspector().locator('#editMilestoneTitle').isDisabled(), true);
  assert.ok(await inspector().getByRole('button', { name: 'Save changes', exact: true }).isVisible());
  await inspector().getByRole('region', { name: 'Course materials', exact: true }).waitFor();
  await inspector().getByRole('button', { name: 'Close inspector', exact: true }).click();
  console.log('PASS: existing milestone validation, draft-local edits, standard-content restrictions, stamp controls and materials inspector');

  stage = 'library and toolbar actions';
  await page.getByRole('button', { name: 'Open milestone library', exact: true }).click();
  await page.getByRole('complementary', { name: 'Milestone library', exact: true }).waitFor();
  await inspector().getByRole('textbox', { name: 'Search milestone library' }).fill(definitions[3].code);
  await inspector().getByRole('button', { name: `Add ${definitions[3].title} to its development path`, exact: true }).click();
  await inspector().getByRole('button', { name: 'Close milestone library', exact: true }).click();
  await settle(); assert.equal(await node(definitions[3].code).count(), 1);
  await page.locator('summary').filter({ hasText: 'Canvas options' }).click();
  await page.getByRole('button', { name: 'Arrange', exact: true }).click(); await settle();
  await versions().click();
  await page.getByRole('button', { name: 'Version history', exact: true }).click();
  await page.getByRole('button', { name: 'Close version history', exact: true }).click();
  await versions().click();
  await page.getByRole('button', { name: /^Published v1 ·/ }).click(); await settle();
  assert.equal((await node(definitions[1].code).textContent()).includes('Workspace draft title'), false);
  await page.getByRole('button', { name: 'Edit draft v2', exact: true }).click(); await settle();
  await node(definitions[1].code).getByText('Workspace draft title', { exact: true }).waitFor();
  assert.equal(await node(definitions[3].code).count(), 1);
  console.log('PASS: on-demand library add, canvas Arrange, consolidated version history and published/draft switching without losing edits');

  stage = 'mobile inspector and resize preservation';
  await page.setViewportSize({ width: 390, height: 844 }); await settle();
  await page.getByRole('combobox', { name: 'Development path', exact: true }).selectOption('ONBOARDING');
  await page.getByRole('button', { name: `Inspect ${definitions[1].code}`, exact: true }).click();
  await page.getByRole('dialog', { name: 'Milestone inspector', exact: true }).waitFor();
  assert.equal(await inspector().evaluate(element => element.matches(':modal')), true);
  await inspector().locator('#editMilestoneTitle').fill('Preserved while resizing');
  await page.setViewportSize({ width: 1024, height: 900 }); await settle();
  assert.equal(await inspector().locator('#editMilestoneTitle').inputValue(), 'Preserved while resizing');
  assert.equal(await inspector().evaluate(element => element.matches(':modal')), false);
  assert.equal(await inspector().locator('#editMilestoneTitle').evaluate(element => element === document.activeElement), true);
  await page.setViewportSize({ width: 390, height: 844 }); await settle();
  assert.equal(await inspector().locator('#editMilestoneTitle').inputValue(), 'Preserved while resizing');
  await page.keyboard.press('Tab');
  assert.equal(await inspector().evaluate(element => element.contains(document.activeElement)), true);
  await page.keyboard.press('Escape'); await inspector().waitFor({ state: 'hidden' });
  assert.ok(await page.getByRole('button', { name: `Inspect ${definitions[1].code}`, exact: true }).evaluate(element => element === document.activeElement));
  console.log('PASS: native mobile inspector, contained focus, Escape/return focus and unsaved form values retained through breakpoints');

  stage = 'responsive workspace and publishing';
  for (const width of [320, 390, 640, 767, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 }); await settle();
    await noOverflow(`workspace overflow at ${width}`);
    if (width < 768) {
      await page.getByRole('combobox', { name: 'Development path', exact: true }).selectOption('TECHNICAL');
      assert.equal(await page.getByLabel('Learning path outline').locator('article[data-path="ONBOARDING"]').count(), 0);
      await page.getByRole('button', { name: `Inspect ${definitions[2].code}`, exact: true }).click();
    } else {
      await page.getByRole('button', { name: 'Outline view', exact: true }).click();
      if (!await page.getByRole('navigation', { name: 'Focus development path' }).isVisible()) await page.getByRole('button', { name: 'Paths', exact: true }).click();
      await page.getByRole('navigation', { name: 'Focus development path' }).getByRole('button', { name: /^Technical Skills/ }).click();
      await page.getByRole('button', { name: `Inspect ${definitions[2].code}`, exact: true }).click();
    }
    await noOverflow(`inspector overflow at ${width}`);
    const bounds = await inspector().boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1);
    if ([390, 1440].includes(width)) await page.screenshot({ path: `/tmp/builder-workspace-inspector-${width}.png`, fullPage: true });
    await inspector().getByRole('button', { name: 'Close inspector', exact: true }).click();
    await page.getByRole('button', { name: 'Open milestone library', exact: true }).click();
    await noOverflow(`library overflow at ${width}`);
    await inspector().getByRole('button', { name: 'Close milestone library', exact: true }).click();
    if ([390, 1440].includes(width)) await page.screenshot({ path: `/tmp/builder-workspace-${width}.png`, fullPage: true });
  }
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Draft saved.', { exact: true }).waitFor({ timeout: 45000 }); await dismissNotice();
  const draft = await prisma.planVersion.findFirstOrThrow({ where: { planId: plan.id, status: 'DRAFT' }, include: { nodes: true } });
  assert.equal(draft.nodes.length, 4);
  assert.equal(draft.nodes.find(item => item.code === definitions[1].code).title, 'Workspace draft title');
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  const publish = page.getByRole('dialog', { name: 'Publish training plan', exact: true });
  await publish.getByRole('region', { name: 'Version edit summary' }).waitFor();
  assert.equal(await publish.locator('#syncToggle').isChecked(), true);
  await publish.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal((await prisma.traineePlanAssignment.findFirstOrThrow({ where: { traineeId: trainee.id, status: 'ACTIVE' } })).planVersionId, published.id);
  assert.equal((await prisma.traineeProgress.findUniqueOrThrow({ where: { id: stamped.id } })).verificationHash, stamped.verificationHash);
  assert.deepEqual(errors, []);
  console.log('PASS: responsive workspace/inspector/library at 320–1440px, draft persistence, unchanged publish defaults, active assignments and original stamp');
})().catch(error => { console.error(`Builder workspace failed at ${stage}: ${`${error.message || error.name} ${(error.stack || '').split('\n').find(line => /test_builder_workspace_browser.cjs:\d/.test(line)) || ''}`.replace(/https?:\/\/[^\s]+/g, '[URL]').slice(0, 1600)}`); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  await prisma.milestoneDefinition.deleteMany({ where: { id: { in: definitions.map(item => item.id) } } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
