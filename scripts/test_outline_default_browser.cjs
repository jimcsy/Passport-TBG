// PLAYWRIGHT_MODULE=<playwright path> node --env-file=.env scripts/test_outline_default_browser.cjs
const assert = require('node:assert/strict');
require('tsx/cjs');
const { prisma } = require('../lib/db/prisma.ts');
const { verificationData } = require('../lib/stamps/hash.ts');
const { SignJWT } = require('jose');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const prefix = `TC09-${Date.now()}`;
const origin = process.env.OUTLINE_TEST_ORIGIN || 'http://localhost:3100';
let browser, trainer, trainee, plan, stage = 'fixtures';
const definitions = [];
(async () => {
  trainer = await prisma.adminUser.create({ data: { employeeId: prefix, email: `${prefix}@example.invalid`, fullName: 'Outline fixture trainer', passwordHash: 'unused' } });
  trainee = await prisma.trainee.create({ data: { traineeCode: prefix, fullName: 'Outline fixture trainee', email: `${prefix}-trainee@example.invalid`, restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Outline-first curriculum fixture', roleIdentifier: prefix, createdById: trainer.id, status: 'PUBLISHED' } });
  const live = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, publishedById: trainer.id } });
  const draft = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 2, status: 'DRAFT', publishedById: trainer.id } });
  for (let i = 0; i < 4; i++) definitions.push(await prisma.milestoneDefinition.create({ data: { code: `${prefix}-${i}`, title: `Outline fixture competency ${i}`, description: 'Demonstrate this competency and reflect before trainer verification.', path: i < 2 ? 'ONBOARDING' : 'TECHNICAL', orderIndex: i === 1 ? 2 : 1, isStandard: false } }));
  let liveNode;
  for (const version of [live, draft]) {
    const nodes = [];
    for (const def of definitions.slice(0, 3)) nodes.push(await prisma.planNode.create({ data: { planVersionId: version.id, libraryMilestoneId: def.id, code: def.code, title: def.title, description: def.description, path: def.path, orderIndex: def.orderIndex, posX: 0, posY: 0, isCustom: true } }));
    await prisma.planEdge.create({ data: { planVersionId: version.id, sourceNodeId: nodes[0].id, targetNodeId: nodes[1].id } });
    if (version.id === live.id) liveNode = nodes[0];
  }
  const assignment = await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: live.id, assignedById: trainer.id } });
  const stamp = await prisma.traineeProgress.create({ data: { traineeId: trainee.id, planNodeId: liveNode.id, ...verificationData(trainee.id, liveNode.id, trainer.id, new Date(), 'Original outline stamp') } });
  const token = await new SignJWT({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: 'beat_admin_session', value: token, url: origin }]);
  const page = await context.newPage(); page.setDefaultTimeout(20000); page.setDefaultNavigationTimeout(60000);
  const errors = []; page.on('pageerror', error => errors.push(error.name));
  await page.goto(`${origin}/trainer/plans/${plan.id}/builder`, { waitUntil: 'networkidle' });
  const outline = page.getByLabel('Learning path outline');
  const inspector = page.locator('#builder-inspector');
  assert.equal(await page.getByRole('button', { name: 'Outline view', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.react-flow').count(), 0);
  assert.equal(await outline.locator(':scope > details').count(), 5);
  const nav = page.getByRole('navigation', { name: 'Focus development path' });
  assert.equal(await nav.getByRole('button').count(), 6);
  await page.getByRole('button', { name: `Inspect ${definitions[0].code}`, exact: true }).click();
  await inspector.locator('#editMilestoneTitle').fill('Saved completely from outline');
  await inspector.getByRole('button', { name: 'Save changes', exact: true }).click(); await inspector.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: `Move ${definitions[0].code} down`, exact: true }).click();
  assert.equal(await outline.locator('article[data-path="ONBOARDING"]').first().getAttribute('data-milestone-index'), '0');
  assert.ok((await outline.locator('article[data-path="ONBOARDING"]').first().textContent()).includes(definitions[1].code));
  assert.equal(await page.getByRole('button', { name: `Drag ${definitions[0].code} to reorder` }).count(), 1);
  await nav.getByRole('button', { name: /^Technical Skills/ }).click();
  await page.getByRole('button', { name: 'Open milestone library', exact: true }).click();
  await inspector.getByRole('textbox', { name: 'Search milestone library' }).fill(definitions[3].code);
  await inspector.getByRole('button', { name: `Add ${definitions[3].title} to its development path`, exact: true }).click();
  await inspector.getByRole('button', { name: 'Close milestone library' }).click();
  await nav.getByRole('button', { name: 'Whole plan', exact: true }).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click(); await page.getByText('Draft saved.', { exact: true }).waitFor({ timeout: 60000 });
  assert.equal(await page.locator('.react-flow').count(), 0);
  const saved = await prisma.planVersion.findUniqueOrThrow({ where: { id: draft.id }, include: { nodes: true, edges: { include: { sourceNode: true, targetNode: true } } } });
  assert.equal(saved.nodes.length, 4);
  assert.equal(saved.nodes.find(n => n.code === definitions[0].code).title, 'Saved completely from outline');
  assert.equal(saved.nodes.find(n => n.code === definitions[0].code).orderIndex, 2);
  assert.equal(saved.nodes.find(n => n.code === definitions[1].code).orderIndex, 1);
  assert.equal(saved.nodes.find(n => n.code === definitions[3].code).libraryMilestoneId, definitions[3].id);
  assert.equal(saved.edges.length, 1); assert.equal(saved.edges[0].sourceNode.code, definitions[0].code); assert.equal(saved.edges[0].targetNode.code, definitions[1].code);
  await page.screenshot({ path: '/tmp/tc09-outline-desktop.png' });
  console.log('PASS: fresh Outline, five pillars/Whole plan/collapsible rail, inspect/edit/reorder/add/save entirely without Canvas; correct links and dependency preserved');

  stage = 'canvas and staged edits';
  await page.getByRole('button', { name: `Inspect ${definitions[0].code}`, exact: true }).click();
  await inspector.locator('#editMilestoneTitle').fill('Staged across both views');
  await page.getByRole('button', { name: 'Canvas view', exact: true }).click();
  await page.locator('.react-flow').waitFor();
  assert.equal(await inspector.locator('#editMilestoneTitle').inputValue(), 'Staged across both views');
  assert.equal(await page.locator('.react-flow__node-milestone').count(), 4);
  await page.waitForFunction(() => document.querySelectorAll('.react-flow__edge').length >= 5);
  await inspector.getByRole('button', { name: 'Close inspector' }).click();
  await page.getByRole('button', { name: 'Collapse path navigation' }).click();
  await page.locator('summary').filter({ hasText: 'Canvas options' }).click();
  await page.getByRole('button', { name: 'Fit whole plan', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'Canvas options' }).click();
  await page.getByRole('button', { name: 'Arrange', exact: true }).click();
  await page.getByRole('button', { name: 'Outline view', exact: true }).click();
  await page.getByRole('button', { name: `Inspect ${definitions[0].code}`, exact: true }).click();
  assert.equal(await inspector.locator('#editMilestoneTitle').inputValue(), 'Staged across both views');
  for (const width of [390, 1024, 320, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await inspector.locator('#editMilestoneTitle').inputValue(), 'Staged across both views');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}`);
    if (width < 768) { await page.getByRole('dialog', { name: 'Milestone inspector', exact: true }).waitFor(); assert.equal(await inspector.evaluate(el => el.matches(':modal')), true); }
  }
  await inspector.getByRole('button', { name: 'Cancel', exact: true }).click(); await inspector.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Save draft', exact: true }).click(); await page.getByText('Draft saved.', { exact: true }).waitFor({ timeout: 60000 });
  const finalNodes = await prisma.planNode.findMany({ where: { planVersionId: draft.id } });
  assert.equal(finalNodes.length, 4); assert.equal(finalNodes.find(n => n.code === definitions[0].code).title, 'Saved completely from outline');
  const finalEdges = await prisma.planEdge.findMany({ where: { planVersionId: draft.id }, include: { sourceNode: true, targetNode: true } });
  assert.equal(finalEdges.length, 1); assert.equal(finalEdges[0].sourceNode.code, definitions[0].code); assert.equal(finalEdges[0].targetNode.code, definitions[1].code);
  assert.deepEqual(await prisma.traineePlanAssignment.findUniqueOrThrow({ where: { id: assignment.id } }), assignment);
  assert.deepEqual(await prisma.traineeProgress.findUniqueOrThrow({ where: { id: stamp.id } }), stamp);
  assert.deepEqual(await prisma.planNode.findUniqueOrThrow({ where: { id: liveNode.id } }), liveNode);
  await page.getByRole('button', { name: 'Canvas view', exact: true }).click();
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('button', { name: 'Outline view', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.deepEqual(errors, []);
  console.log('PASS: Canvas same nodes/edges, fit/arrange, staged edits across views/resizes, Cancel scope, fresh-session default and unchanged active assignment/published node/stamp');
})().catch(error => { console.error(`Outline default check failed at ${stage}: ${String(error.message).replace(/(?:postgres(?:ql)?|https?):\/\/\S+/g, '[URL]').slice(0, 1800)}`); process.exitCode = 1; }).finally(async () => {
  await browser?.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  await prisma.milestoneDefinition.deleteMany({ where: { id: { in: definitions.map(d => d.id) } } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
