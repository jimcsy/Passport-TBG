// PLAYWRIGHT_BROWSERS_PATH=/tmp/passport-registration-browser/browsers PLAYWRIGHT_MODULE=/tmp/passport-registration-browser/node_modules/playwright node --env-file=.env scripts/test_stamp_notifications_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
require('tsx/cjs');
const { prisma } = require('../lib/db/prisma.ts');
const { STROBI_MASCOT_MAP } = require('../lib/constants/mascots.ts');
const { verifyAssignedMilestones } = require('../lib/db/repositories/verification.ts');
const { SignJWT } = require('jose');
const assert = require('node:assert/strict');
const origin = process.env.STROBI_TEST_ORIGIN || 'http://localhost:3100';
let browser, trainer, trainee, plan;
(async () => {
  const suffix = String(Date.now());
  trainer = await prisma.adminUser.create({ data: { employeeId: `STROBI-${suffix}`, email: `strobi-${suffix}@example.invalid`, fullName: 'Strobi Test Trainer', passwordHash: 'unused-test-password' } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Strobi browser fixture', roleIdentifier: 'STROBI_TEST', status: 'PUBLISHED', createdById: trainer.id } });
  const version = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, status: 'PUBLISHED', publishedById: trainer.id } });
  const nodes = [];
  for (const [path, mascot] of Object.entries(STROBI_MASCOT_MAP)) {
    nodes.push(await prisma.planNode.create({ data: { planVersionId: version.id, path, code: `STROBI-${suffix}-${path}`, title: `${mascot.category} celebration test`, description: 'Isolated Strobi browser check', orderIndex: 1, posX: 0, posY: 0 } }));
  }
  trainee = await prisma.trainee.create({ data: { traineeCode: `STROBI-${suffix}`, fullName: 'Strobi Test Trainee', email: `strobit-${suffix}@example.invalid`, restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: version.id, assignedById: trainer.id } });
  await prisma.traineeProgress.createMany({ data: nodes.map(node => ({ traineeId: trainee.id, planNodeId: node.id, status: 'READY_FOR_REVIEW', traineeNote: 'Strobi integration test', requestedAt: new Date() })) });
  browser = await chromium.launch({ headless: true });
  async function context(payload, name) {
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    const token = await new SignJWT(payload).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
    await ctx.addCookies([{ name, value: token, url: origin }]);
    return ctx;
  }
  const learner = await context({ id: trainee.id, traineeCode: trainee.traineeCode, fullName: trainee.fullName, email: trainee.email, portal: 'trainee' }, 'beat_trainee_session');
  // An award made before the dashboard loads must still be discoverable.
  await verifyAssignedMilestones([trainee.id], nodes[0].id, trainer.id, 'Offline award feedback');
  const page = await learner.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install();
  await page.goto(origin + '/trainee/dashboard', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Stamp notifications', exact: true });
  const box = await panel.boundingBox();
  assert(box.width <= 320, 'Notifications must be a compact panel');
  await panel.getByRole('button', { name: 'Unread: Onboarding celebration test', exact: true }).click();
  let celebration = page.getByRole('dialog', { name: 'New stamp earned!', exact: true });
  await celebration.getByText('Strobi the Sprinter', { exact: true }).waitFor();
  assert.equal(await celebration.locator('canvas').count(), 1);
  await celebration.getByRole('button', { name: 'Continue learning', exact: true }).click();
  await page.waitForURL('**/modules/' + nodes[0].id);
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Notifications', exact: true }).click();
  await panel.getByRole('button', { name: 'Read: Onboarding celebration test', exact: true }).click();
  await page.waitForURL('**/modules/' + nodes[0].id);
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await prisma.stampNotificationRead.count({ where: { traineeId: trainee.id } }), 1);
  console.log('PASS: approval before page load is unread, compact bell panel, first opening celebrates, persisted read state and repeated opening navigates to module');
  const otherDevice = await browser.newContext({ storageState: await learner.storageState() });
  const otherPage = await otherDevice.newPage();
  await otherPage.goto(origin + '/trainee/dashboard', { waitUntil: 'networkidle' });
  await otherPage.getByRole('button', { name: 'Notifications', exact: true }).click();
  await otherPage.getByRole('button', { name: 'Read: Onboarding celebration test', exact: true }).click();
  await otherPage.waitForURL('**/modules/' + nodes[0].id);
  assert.equal(await otherPage.getByRole('dialog').count(), 0);
  await otherDevice.close();
  await page.goto(origin + '/trainee/dashboard/booklet', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Notifications', exact: true }).waitFor();
  const staff = await context({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }, 'beat_admin_session');
  const admin = await staff.newPage();
  await admin.goto(origin + '/trainer/queue', { waitUntil: 'networkidle' });
  const toggle = admin.getByRole('button', { name: new RegExp(nodes[1].code + ':') });
  await toggle.click();
  await toggle.locator('..').getByRole('button', { name: '1-Click Verify & Stamp', exact: true }).click();
  await admin.getByText('Stamped & Verified!', { exact: true }).waitFor();
  await page.bringToFront();
  await page.clock.fastForward(30001);
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).waitFor({ timeout: 45000 });
  assert.equal(await page.getByRole('dialog').count(), 0, 'Polling should notify without interrupting learning');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Notifications, 1 unread', exact: true }).click();
  const mobileBox = await panel.boundingBox();
  assert(mobileBox.x >= 0 && mobileBox.x + mobileBox.width <= 390);
  await panel.getByRole('button', { name: 'Unread: Communication Skills celebration test', exact: true }).click();
  celebration = page.getByRole('dialog', { name: 'New stamp earned!', exact: true });
  await celebration.getByText('Strobi the Speaker', { exact: true }).waitFor();
  assert.equal(await celebration.locator('canvas').count(), 0);
  await page.keyboard.press('Escape');
  await page.waitForURL('**/modules/' + nodes[1].id);
  await page.getByRole('button', { name: 'Notifications', exact: true }).click();
  await panel.getByRole('button', { name: 'Read: Communication Skills celebration test', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await panel.waitFor({ state: 'detached' });
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Notifications');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: read state survives a second device, actual trainer approval polls in passport, no unsolicited modal, mobile compact panel, matching first-open celebration, reduced motion and keyboard dismissal');
})().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
