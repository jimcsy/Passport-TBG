// Optional browser tooling stays outside project dependencies.
// PLAYWRIGHT_MODULE=/tmp/passport-browser/node_modules/playwright node --env-file=.env scripts/test_stamp_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { createRequire } = require('node:module');
const project = createRequire(process.cwd() + '/package.json');
project('tsx/cjs');
const { prisma } = project('./lib/db/prisma.ts');
const { SignJWT } = project('jose');
const { verificationData } = project('./lib/stamps/hash.ts');
const assert = require('node:assert/strict');
const origin = 'http://localhost:3100';
let browser, plan, trainee, trainer;
(async () => {
  const suffix = Date.now().toString();
  trainer = await prisma.adminUser.create({ data: { employeeId: 'STAMP-' + suffix, email: `stamp-${suffix}@example.invalid`, fullName: 'Stamp Browser Trainer', role: 'TRAINER', passwordHash: 'unused-test-password' } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Stamp Browser Fixture', roleIdentifier: 'STAMP_BROWSER', status: 'PUBLISHED', createdById: trainer.id } });
  const version = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, status: 'PUBLISHED', publishedById: trainer.id } });
  const first = await prisma.planNode.create({ data: { planVersionId: version.id, code: 'STAMP-BROWSE-01', title: 'Browser approval', description: 'Check trainer approval and trainee polling', path: 'ONBOARDING', stampDesign: 'BARISTA_BADGE', orderIndex: 1, posX: 0, posY: 0 } });
  const second = await prisma.planNode.create({ data: { planVersionId: version.id, code: 'STAMP-BROWSE-02', title: 'Existing approval', description: 'Check tooltip audit fields', path: 'ONBOARDING', stampDesign: 'SERVICE_BADGE', orderIndex: 2, posX: 0, posY: 200 } });
  trainee = await prisma.trainee.create({ data: { traineeCode: 'STAMP-' + suffix, fullName: 'Stamp Browser Trainee', email: `trainee-${suffix}@example.invalid`, restaurantBrand: 'Stamp Browser Brand', branchLocation: 'Test', cohortBatch: 'Stamp browser test', hireDate: new Date() } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: trainee.id, planVersionId: version.id, assignedById: trainer.id } });
  await prisma.traineeProgress.create({ data: { traineeId: trainee.id, planNodeId: first.id, status: 'READY_FOR_REVIEW', traineeNote: 'My browser reflection', requestedAt: new Date() } });
  const approval = verificationData(trainee.id, second.id, trainer.id, new Date(), 'Existing trainer feedback');
  await prisma.traineeProgress.create({ data: { traineeId: trainee.id, planNodeId: second.id, traineeNote: 'Existing trainee reflection', ...approval } });
  console.log('Isolated stamp fixtures created');
  browser = await chromium.launch({ executablePath: process.env.STAMP_BROWSER_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  async function context(payload, name, viewport = { width: 1280, height: 1000 }) {
    const ctx = await browser.newContext({ viewport });
    const key = new TextEncoder().encode(process.env.SESSION_SECRET || 'beat-growth-passport-super-secret-key-change-in-production-2024');
    const token = await new SignJWT(payload).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(key);
    await ctx.addCookies([{ name, value: token, url: origin }]);
    return ctx;
  }
  const traineePayload = { id: trainee.id, traineeCode: trainee.traineeCode, fullName: trainee.fullName, email: trainee.email, portal: 'trainee' };
  const learner = await context(traineePayload, 'beat_trainee_session');
  const page = await learner.newPage();
  await page.clock.install();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/trainee/dashboard', { waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Learning overview' }).waitFor();
  console.log('Dashboard loaded');
  await page.goto(origin + '/trainee/dashboard/booklet', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Onboarding/ }).first().click();
  const ghost = page.getByRole('img', { name: 'Barista stamp, unverified', exact: true }).first();
  assert.equal(await ghost.evaluate(element => getComputedStyle(element).opacity), '0.25');
  await page.goto(origin + '/trainee/dashboard', { waitUntil: 'networkidle' });
  console.log('PASS: unverified stamp uses 25% opacity');
  const staff = await context({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, email: trainer.email, role: 'TRAINER', portal: 'trainer' }, 'beat_admin_session');
  const adminPage = await staff.newPage();
  await adminPage.goto(origin + '/trainer/queue', { waitUntil: 'networkidle' });
  await adminPage.getByRole('button', { name: /STAMP-BROWSE-01: Browser approval/ }).click();
  await adminPage.getByRole('button', { name: '+ Add feedback note', exact: true }).last().click();
  // Scope to our expanded card rather than other trainees' queue items.
  await adminPage.locator(`input[id^="trainer-note-"]`).last().fill('Browser verified feedback');
  const card = adminPage.getByRole('button', { name: /STAMP-BROWSE-01: Browser approval/ }).locator('..');
  await card.getByRole('button', { name: '1-Click Verify & Stamp' }).click();
  await adminPage.getByText('Stamped & Verified!', { exact: true }).waitFor();
  const persisted = await prisma.traineeProgress.findUniqueOrThrow({ where: { traineeId_planNodeId: { traineeId: trainee.id, planNodeId: first.id } } });
  assert.equal(persisted.status, 'VERIFIED');
  assert.equal(persisted.verificationHash, verificationData(trainee.id, first.id, trainer.id, persisted.verifiedAt).verificationHash);
  console.log('Approval persisted; returning trainee tab to foreground');
  await page.bringToFront();
  console.log('Trainee visibility:', await page.evaluate(() => document.visibilityState));
  await page.clock.fastForward(30001);
  await page.getByText('🎉 New stamp earned!', { exact: true }).waitFor({ timeout: 45000 });
  console.log('PASS: actual trainer action stores hash; 30-second polling refreshes and displays toast');
  await page.goto(origin + '/trainee/dashboard/booklet', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: /Onboarding/ }).first().click();
  const stamp = page.getByRole('button', { name: 'Existing approval: verified and stamped, view details' }).first();
  await stamp.hover();
  const tooltip = page.getByRole('tooltip').first();
  await tooltip.waitFor();
  for (const text of ['STAMP-BROWSE-02: Existing approval', 'Stamp Browser Trainer', approval.verificationHash.slice(0, 8), 'Existing trainee reflection', 'Existing trainer feedback']) assert.ok(await tooltip.getByText(text, { exact: true }).isVisible(), text);
  assert.ok(await tooltip.getByText('Verified at', { exact: true }).isVisible());
  console.log('PASS: hover tooltip shows all six audit metadata fields');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.mouse.move(0, 0);
  await stamp.click();
  assert.ok(await page.getByRole('tooltip').first().isVisible());
  console.log('PASS: mobile-width tap opens stamp metadata');
  await adminPage.goto(origin + `/trainer/plans/${plan.id}/builder`, { waitUntil: 'networkidle' });
  await adminPage.getByRole('button', { name: 'New draft', exact: true }).click();
  await adminPage.getByRole('button', { name: 'Draft v2', exact: true }).waitFor();
  const edit = adminPage.getByRole('button', { name: 'Edit Milestone', exact: true }).first();
  await edit.click({ force: true });
  const dialog = adminPage.getByRole('dialog', { name: 'Edit milestone' });
  const previews = dialog.locator('fieldset').first().locator('svg[role=img]');
  assert.equal(await previews.count(), 8);
  const signatures = await previews.evaluateAll(elements => elements.map(element => element.innerHTML));
  assert.equal(new Set(signatures).size, 8);
  assert.equal(await previews.first().evaluate(element => getComputedStyle(element).opacity), '1');
  await dialog.getByRole('button', { name: /Kitchen/ }).click();
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click();
  await adminPage.getByRole('button', { name: 'Save draft', exact: true }).click();
  await adminPage.getByText('Draft saved.', { exact: true }).waitFor();
  const draft = await prisma.planVersion.findFirstOrThrow({ where: { planId: plan.id, status: 'DRAFT' }, include: { nodes: true } });
  assert.ok(draft.nodes.some(node => node.stampDesign === 'KITCHEN_BADGE'), JSON.stringify(draft.nodes.map(node => ({ code: node.code, design: node.stampDesign }))));
  console.log('PASS: standard milestone design picker saves the selected stamp to draft');
  assert.deepEqual(errors, []);
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
