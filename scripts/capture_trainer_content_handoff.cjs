// Production server: port 3100. Supply PLAYWRIGHT_MODULE/BROWSERS_PATH if external.
// Uses disposable records and a real temporary PDF, never real trainee assignments.
require('tsx/cjs');
const assert = require('node:assert/strict');
const { mkdirSync } = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { SignJWT } = require('jose');
const { createClient } = require('@supabase/supabase-js');
const { prisma } = require('../lib/db/prisma.ts');
const origin = 'http://localhost:3100';
const prefix = `TC12-${Date.now()}`;
const code = `HD-${String(Date.now()).slice(-8)}`;
const directory = 'docs/images/trainer-content';
let trainer, plan, browser, page, stage = 'fixtures';
const storage = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
(async () => {
  mkdirSync(directory, { recursive: true });
  trainer = await prisma.adminUser.create({ data: { employeeId: prefix, fullName: 'Workspace guide trainer', email: `${prefix}@example.invalid`, passwordHash: 'unused' } });
  const base = await prisma.milestoneDefinition.create({ data: { code: `${code}-BASE`, title: 'Practice the workplace safety checklist', description: 'Complete the safety checklist with your trainer and reflect on the procedure.', path: 'TECHNICAL', isStandard: false } });
  plan = await prisma.trainingPlan.create({ data: { title: 'Workspace walkthrough track', roleIdentifier: prefix, status: 'DRAFT', createdById: trainer.id } });
  const master = await prisma.learningPath.findFirstOrThrow({ where: { type: 'MASTER', isTemplate: true }, select: { id: true } });
  await prisma.learningPath.create({ data: { planId: plan.id, title: plan.title, type: 'VARIANT', parentId: master.id, targetDepartment: 'Operations Department', targetPosition: 'Quality Assurance Manager' } });
  const draft = await prisma.planVersion.create({ data: { planId: plan.id, versionNumber: 1, status: 'DRAFT', publishedById: trainer.id } });
  await prisma.planNode.create({ data: { planVersionId: draft.id, libraryMilestoneId: base.id, code: base.code, title: base.title, description: base.description, path: base.path, orderIndex: 1, posX: 0, posY: 0, isCustom: true } });
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const token = await new SignJWT({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  await context.addCookies([{ name: 'beat_admin_session', value: token, url: origin }]);
  page = await context.newPage(); page.setDefaultTimeout(60000); page.setDefaultNavigationTimeout(60000);
  const errors = []; page.on('pageerror', error => errors.push(error.name));
  const capture = async name => {
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name} fits its viewport`);
    await page.screenshot({ path: `${directory}/${name}.png` });
  };
  stage = 'catalog';
  await page.goto(`${origin}/trainer/plans`, { waitUntil: 'networkidle' });
  await page.getByRole('searchbox', { name: 'Search role variants' }).fill(plan.title);
  await page.getByRole('article', { name: plan.title, exact: true }).waitFor();
  await capture('plans-desktop');
  stage = 'create and upload';
  await page.goto(`${origin}/trainer/plans/library?q=${code}`, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Create milestone', exact: true }).click();
  const form = page.getByRole('form', { name: 'Create shared milestone', exact: true });
  await form.locator('input[name=code]').fill(code);
  await form.locator('input[name=title]').fill('Practice the equipment handover');
  await form.locator('textarea[name=description]').fill('Review the handover material, practice the procedure, and discuss your reflection with your trainer.');
  await form.getByRole('combobox').selectOption('TECHNICAL');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole('dialog', { name: 'Shared library milestone inspector', exact: true }).waitFor();
  await capture('create-mobile');
  await form.getByRole('button', { name: 'Save shared milestone' }).click();
  const inspector = page.locator('#library-inspector');
  const upload = inspector.getByLabel(`Attach materials to ${code}`); await upload.waitFor();
  await upload.setInputFiles({ name: 'equipment-handover-guide.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n%%EOF\n') });
  await inspector.getByRole('heading', { name: 'Course materials (1)', exact: true }).waitFor();
  await inspector.getByRole('button', { name: 'Preview / download', exact: true }).click();
  const preview = page.getByRole('dialog', { name: 'equipment-handover-guide.pdf', exact: true });
  await preview.waitFor(); await preview.getByRole('button', { name: 'Close material preview' }).click();
  await preview.waitFor({ state: 'hidden' });
  await inspector.getByRole('heading', { name: 'Course materials (1)', exact: true }).scrollIntoViewIfNeeded();
  await capture('materials-mobile');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await inspector.getByRole('heading', { name: 'Course materials (1)', exact: true }).scrollIntoViewIfNeeded();
  await capture('library-desktop');
  stage = 'insert arrange save reload';
  await inspector.getByRole('button', { name: 'Add to plan', exact: true }).click();
  await inspector.getByRole('combobox', { name: 'Training plan', exact: true }).selectOption(plan.id);
  await inspector.getByRole('link', { name: 'Open plan to add', exact: true }).click();
  const banner = page.getByRole('region', { name: 'Milestone add request', exact: true });
  await banner.getByRole('button', { name: 'Add to this draft', exact: true }).click();
  await banner.getByRole('button', { name: 'Dismiss add request', exact: true }).click();
  await page.getByRole('button', { name: `Move ${code} up`, exact: true }).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Draft saved.', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'networkidle' });
  await banner.getByRole('button', { name: 'Dismiss add request', exact: true }).click();
  await banner.waitFor({ state: 'hidden' });
  const shared = await prisma.milestoneDefinition.findUniqueOrThrow({ where: { code } });
  const saved = await prisma.planNode.findFirstOrThrow({ where: { planVersionId: draft.id, libraryMilestoneId: shared.id } });
  assert.equal(saved.orderIndex, 1);
  await page.getByRole('navigation', { name: 'Focus development path' }).getByRole('button', { name: /^Technical Skills/ }).click();
  await capture('outline-desktop');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole('combobox', { name: 'Development path', exact: true }).selectOption('TECHNICAL');
  await capture('outline-mobile');
  stage = 'publish review';
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  const publish = page.getByRole('dialog', { name: 'Publish training plan', exact: true });
  await publish.getByRole('region', { name: 'Version edit summary', exact: true }).waitFor();
  await capture('publish-mobile');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await capture('publish-desktop');
  await publish.getByRole('button', { name: 'Publish Version 1', exact: true }).click();
  await publish.waitFor({ state: 'detached', timeout: 180000 });
  assert.equal((await prisma.planVersion.findUniqueOrThrow({ where: { id: draft.id } })).status, 'PUBLISHED');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('button', { name: 'Save draft', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile create, real upload, preview, explicit insertion, reorder, save, reload, impact review, publish and read-only inspection; eight screenshots captured');
})().catch(async error => { if (page && !page.isClosed()) await page.screenshot({ path: '/tmp/tc12-review-failure.png' }); console.error(`Handoff review failed at ${stage}: ${String(error.message).replace(/(?:postgres(?:ql)?|https?):\/\/\S+/g, '[URL]').slice(0, 1800)}`); process.exitCode = 1; }).finally(async () => {
  await browser?.close();
  if (trainer) {
    const materials = await prisma.courseMaterial.findMany({ where: { uploadedById: trainer.id }, select: { storagePath: true } });
    if (materials.length && (await storage.storage.from('course-materials').remove(materials.map(item => item.storagePath))).error) { console.error('Temporary Storage cleanup failed'); process.exitCode = 1; }
  }
  if (plan) await prisma.trainingPlan.delete({ where: { id: plan.id } });
  await prisma.milestoneDefinition.deleteMany({ where: { code: { in: [code, `${code}-BASE`] } } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
