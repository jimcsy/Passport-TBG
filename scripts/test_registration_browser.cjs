// PLAYWRIGHT_MODULE=/tmp/passport-registration-browser/node_modules/playwright node --env-file=.env scripts/test_registration_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
require('tsx/cjs');
const { prisma } = require('../lib/db/prisma.ts');
const { SignJWT } = require('jose');
const assert = require('node:assert/strict');
const { FOUNDATION_PLAN_ID } = require('../lib/constants/foundation.ts');
const origin = process.env.REGISTRATION_TEST_ORIGIN || 'http://localhost:3100';
let browser, trainer;
const suffix = String(Date.now());
const code = `REG-${suffix}`;
(async () => {
  trainer = await prisma.adminUser.create({ data: { employeeId: `REG-${suffix}`, email: `reg-${suffix}@example.invalid`, fullName: 'Registration Test Trainer', passwordHash: 'unused-fixture-password' } });
  const version = await prisma.planVersion.findFirstOrThrow({ where: { planId: FOUNDATION_PLAN_ID, status: 'PUBLISHED' }, orderBy: { versionNumber: 'desc' }, include: { nodes: true } });
  browser = await chromium.launch({ executablePath: process.env.PATH_BROWSER_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const token = await new SignJWT({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('30m').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  await context.addCookies([{ name: 'beat_admin_session', value: token, url: origin }]);
  const page = await context.newPage();
  await page.goto(`${origin}/trainer/trainees/new`, { waitUntil: 'networkidle' });
  const department = page.getByLabel('Department', { exact: false });
  const position = page.getByLabel('Position', { exact: false });
  assert.equal(await position.isDisabled(), true);
  assert.equal(await department.locator('option').count(), 19);
  await department.selectOption('ICT Department');
  assert.equal(await position.isEnabled(), true);
  await position.selectOption('Application Developer');
  await department.selectOption('Finance Department');
  assert.equal(await position.inputValue(), '');
  assert.equal(await position.locator('option[value="Application Developer"]').count(), 0);
  await position.selectOption('Accounting Assistant');
  await department.selectOption('');
  assert.equal(await position.inputValue(), '');
  assert.equal(await position.isDisabled(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await department.selectOption('ICT Department');
  await position.selectOption('Application Developer');
  assert.equal(await page.locator('select[name="planVersionId"]').count(), 0);
  await page.getByText('Foundation Level 1: TBG Corporate Onboarding', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  console.log('PASS: initial disable, department filtering, selected-position reset, clearing department, mobile layout and fixed foundation display');
  await page.locator('#fullName').fill('Registration Browser Test');
  await page.locator('#email').fill(`reg-${suffix}@example.invalid`);
  await page.locator('#traineeCode').fill(code);
  await page.locator('#hireDate').fill('2026-10-29');
  await page.locator('#restaurantBrand').fill('Corporate Head Office');
  await page.locator('#branchLocation').fill('Registration Test');
  await page.locator('#cohortBatch').fill('Registration Test');
  // Bypass the UI option restrictions to confirm server-side pair validation.
  await position.evaluate(select => { select.add(new Option('President', 'President')); });
  await position.selectOption('President');
  await page.getByRole('button', { name: 'Register trainee', exact: true }).click();
  await page.getByText('Select a position belonging to the selected department.', { exact: true }).waitFor();
  assert.equal(await prisma.trainee.count({ where: { traineeCode: code } }), 0);
  await position.selectOption('Application Developer');
  await page.getByRole('button', { name: 'Register trainee', exact: true }).click();
  await page.getByRole('heading', { name: 'Trainee registered', exact: true }).waitFor({ timeout: 45000 });
  const created = await prisma.trainee.findUniqueOrThrow({ where: { traineeCode: code }, include: { planAssignments: true, progressRecords: true } });
  assert.equal(created.department, 'ICT Department');
  assert.equal(created.position, 'Application Developer');
  assert.equal(created.jobRole, created.position);
  assert.equal(created.planAssignments.length, 1);
  const instance = await prisma.learningPath.findFirstOrThrow({ where: { traineeId: created.id, type: "INSTANCE" } });
  assert.equal(instance.sourceVersionId, version.id);
  assert.equal(instance.parentId, FOUNDATION_PLAN_ID);
  assert.notEqual(created.planAssignments[0].planVersionId, version.id);
  assert.equal(created.progressRecords.length, version.nodes.length);
  assert.ok(created.progressRecords.every(record => record.status === 'IN_PROGRESS' && !record.isArchived));
  await page.getByRole('button', { name: 'Register another trainee', exact: true }).click();
  assert.equal(await department.inputValue(), '');
  assert.equal(await position.inputValue(), '');
  assert.equal(await position.isDisabled(), true);
  console.log('PASS: forged mismatch rejected without records; valid registration persists organization, assigns only foundation, initializes progress, and resets for next trainee');
})().catch(() => { console.error('Registration browser check failed; credentials and session details redacted.'); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  const instances = await prisma.learningPath.findMany({ where: { trainee: { traineeCode: code }, type: "INSTANCE" }, select: { planId: true } });
  await prisma.trainee.deleteMany({ where: { traineeCode: code } });
  await prisma.trainingPlan.deleteMany({ where: { id: { in: instances.map(path => path.planId) } } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
