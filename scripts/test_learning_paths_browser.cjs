// PLAYWRIGHT_MODULE=/tmp/passport-registration-browser/node_modules/playwright node --env-file=.env scripts/test_learning_paths_browser.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
require('tsx/cjs');
const { prisma } = require('../lib/db/prisma.ts');
const { SignJWT } = require('jose');
const assert = require('node:assert/strict');
const { assignPlanToTrainee } = require('../lib/db/repositories/assignments.ts');
const { savePlanVersion, publishPlanVersion } = require('../lib/db/repositories/plans.ts');
const { verificationData } = require('../lib/stamps/hash.ts');
const origin = process.env.CATALOG_TEST_ORIGIN || 'http://localhost:3100';
const suffix = String(Date.now());
let trainer, trainee, legacy, browser, stage = 'fixtures';
(async () => {
  trainer = await prisma.adminUser.create({ data: { employeeId: `CAT-${suffix}`, email: `cat-${suffix}@example.invalid`, fullName: 'Catalog Browser Trainer', passwordHash: 'unused-test-password' } });
  trainee = await prisma.trainee.create({ data: { traineeCode: `CAT-${suffix}`, fullName: 'Catalog Browser Trainee', email: `catt-${suffix}@example.invalid`, department: 'ERP Department', position: 'Junior ERP Analyst', restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  const token = await new SignJWT({ id: trainer.id, employeeId: trainer.employeeId, fullName: trainer.fullName, role: 'TRAINER', portal: 'trainer' }).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('1h').sign(new TextEncoder().encode(process.env.SESSION_SECRET));
  let page;
  async function freshPage(path, mobile = false) {
    if (browser) await browser.close();
    browser = await chromium.launch({ ...(process.env.CATALOG_BROWSER_EXECUTABLE ? { executablePath: process.env.CATALOG_BROWSER_EXECUTABLE } : {}), headless: true });
    const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1280, height: 900 } });
    await context.addCookies([{ name: 'beat_admin_session', value: token, url: origin }]);
    page = await context.newPage(); page.setDefaultTimeout(15000);
    await page.goto(`${origin}${path}`, { waitUntil: 'networkidle' });
  }
  stage = 'catalog and create';
  await freshPage('/trainer/plans');
  assert.equal(await page.getByRole('region', { name: 'Master training plan' }).count(), 1);
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByRole('heading', { name: 'Foundation Level 1: TBG Corporate Onboarding', exact: true }).waitFor();
  assert.equal(await page.getByRole('navigation', { name: 'Training content', exact: true }).getByRole('link', { name: 'Training Plans', exact: true }).getAttribute('aria-current'), 'page');
  assert.equal(await page.getByRole('link', { name: 'trainee profiles', exact: true }).getAttribute('href'), '/trainer/trainees');
  // Repeated quick-action entry on the mounted catalog must reopen the inline form.
  await page.setViewportSize({ width: 390, height: 844 });
  for (let attempt = 0; attempt < 2; attempt++) {
    await page.getByRole('button', { name: 'Open quick actions', exact: true }).click();
    await page.getByRole('link', { name: 'Create role variant', exact: true }).click();
    const createForm = page.getByRole('form', { name: 'Create role variant', exact: true });
    await createForm.waitFor();
    assert.equal(await page.getByRole('dialog').count(), 0);
    await createForm.getByRole('button', { name: 'Cancel', exact: true }).click();
    await createForm.waitFor({ state: 'detached' });
  }
  await page.setViewportSize({ width: 1280, height: 900 });
  const initialTitle = `ERP Browser ${suffix}`;
  await page.getByRole('button', { name: 'Create role variant', exact: true }).click();
  let dialog = page.getByRole('form', { name: 'Create role variant', exact: true });
  await dialog.getByLabel('Variant Title', { exact: true }).fill(initialTitle);
  await dialog.getByLabel('Target Department', { exact: true }).selectOption('ERP Department');
  await dialog.getByLabel('Target Position', { exact: true }).selectOption('Junior ERP Analyst');
  await dialog.getByRole('button', { name: 'Create Variant', exact: true }).click();
  await dialog.waitFor({ state: 'detached', timeout: 45000 });
  await page.getByRole('heading', { name: initialTitle, exact: true }).waitFor();
  await browser.close(); browser = undefined;
  const variant = await prisma.learningPath.findFirstOrThrow({ where: { title: initialTitle, type: 'VARIANT' } });
  const version = await prisma.planVersion.findFirstOrThrow({ where: { planId: variant.planId } });
  await publishPlanVersion({ versionId: version.id, syncTrainees: false }, trainer.id);
  const assigned = await assignPlanToTrainee({ traineeId: trainee.id, planVersionId: version.id, assignedById: trainer.id });
  const instance = await prisma.learningPath.findUniqueOrThrow({ where: { planId: assigned.assignment.planVersion.planId } });
  const originalProgress = await prisma.traineeProgress.findFirstOrThrow({ where: { traineeId: trainee.id } });
  const stamp = await prisma.traineeProgress.update({ where: { id: originalProgress.id }, data: verificationData(trainee.id, originalProgress.planNodeId, trainer.id, new Date(), 'Retained catalog audit') });
  const instanceNodes = await prisma.planNode.findMany({ where: { planVersionId: assigned.assignment.planVersionId } });
  const changed = await savePlanVersion({ planId: instance.planId, publishedById: trainer.id, status: 'DRAFT', nodes: [...instanceNodes, { code: `CAT-${suffix}-EXTRA`, title: 'Individual ERP competency', description: 'Customized trainee-specific competency', path: 'TECHNICAL', orderIndex: 5, posX: 0, posY: 0, isCustom: true }], edges: [] });
  await publishPlanVersion({ versionId: changed.id, syncTrainees: true }, trainer.id);
  console.log('PASS: one master summary, inline variant creation, foundation copy and private customized trainee instance');

  stage = 'rename and edit nodes';
  await freshPage('/trainer/plans');
  const row = page.getByRole('article', { name: initialTitle, exact: true });
  assert.equal(await page.getByRole('region', { name: 'Master training plan', exact: true }).count(), 1);
  assert.ok(await row.getByText('1 enrolled trainee', { exact: true }).isVisible());
  assert.equal(await page.locator(`a[href="/trainer/plans/${instance.planId}/builder"]`).count(), 0);
  await row.getByRole('button', { name: 'Edit details', exact: true }).click();
  dialog = page.getByRole('form', { name: `Edit details for ${initialTitle}`, exact: true });
  const renamed = `Renamed ERP ${suffix}`;
  await dialog.getByLabel('Variant Title', { exact: true }).fill(renamed);
  await dialog.getByLabel('Target Department', { exact: true }).selectOption('Finance Department');
  assert.equal(await dialog.getByLabel('Target Position', { exact: true }).inputValue(), '');
  await dialog.getByLabel('Target Position', { exact: true }).selectOption('Accounting Assistant');
  await dialog.getByText('Quick milestone edits (20)', { exact: true }).click();
  await dialog.getByRole('button', { name: 'Move ONB-01 down', exact: true }).click();
  await dialog.getByRole('button', { name: 'Add milestone to Technical Skills', exact: true }).click();
  await dialog.getByRole('button', { name: 'Save Variant', exact: true }).click();
  await dialog.waitFor({ state: 'detached', timeout: 45000 });
  await page.getByRole('heading', { name: renamed, exact: true }).waitFor();
  const draft = await prisma.planVersion.findFirstOrThrow({ where: { planId: variant.planId, status: 'DRAFT' }, include: { nodes: true } });
  assert.equal(draft.nodes.length, 21);
  assert.equal(draft.nodes.find(node => node.code === 'ONB-01').orderIndex, 2);
  assert.equal((await prisma.learningPath.findUniqueOrThrow({ where: { id: instance.id } })).title, initialTitle);
  const kept = await prisma.traineeProgress.findUniqueOrThrow({ where: { id: stamp.id } });
  assert.equal(kept.status, stamp.status); assert.equal(kept.verificationHash, stamp.verificationHash);
  console.log('PASS: inline editing renames, retags, resets position, reorders and appends draft nodes without changing active instance title/stamp');

  stage = 'profile promotion';
  await freshPage(`/trainer/trainees/${trainee.id}`);
  await page.getByRole('region', { name: 'Active path instance', exact: true }).waitFor();
  assert.equal(await page.getByRole('link', { name: 'Customize Individual Path', exact: true }).getAttribute('href'), `/trainer/plans/${instance.planId}/builder`);
  await page.getByRole('button', { name: 'Promote to Reusable Variant', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Promote to Reusable Variant', exact: true });
  const promotedTitle = `Promoted ERP ${suffix}`;
  await dialog.getByLabel('Variant Title', { exact: true }).fill(promotedTitle);
  await dialog.getByRole('button', { name: 'Create Reusable Variant', exact: true }).click();
  await dialog.waitFor({ state: 'detached', timeout: 45000 });
  const promoted = await prisma.learningPath.findFirstOrThrow({ where: { title: promotedTitle, type: 'VARIANT' } });
  assert.equal((await prisma.planNode.count({ where: { planVersion: { planId: promoted.planId } } })), 21);
  assert.equal(await prisma.traineeProgress.count({ where: { planNode: { planVersion: { planId: promoted.planId } } } }), 0);
  await freshPage('/trainer/plans');
  await page.getByRole('heading', { name: promotedTitle, exact: true }).waitFor();
  const search = page.getByRole('searchbox', { name: 'Search role variants' });
  await search.fill(renamed);
  assert.equal(await page.getByRole('list', { name: 'Role variants', exact: true }).getByRole('article').count(), 1);
  const inlineRow = page.getByRole('article', { name: renamed, exact: true });
  assert.equal(await inlineRow.getByRole('link', { name: 'Edit plan', exact: true }).getAttribute('href'), `/trainer/plans/${variant.planId}/builder`);
  await inlineRow.getByRole('button', { name: 'Edit details', exact: true }).click();
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.getByRole('textbox', { name: 'Variant Title', exact: true }).evaluate(el => el === document.activeElement), true);
  await page.getByRole('textbox', { name: 'Variant Title', exact: true }).fill('Cancelled rename');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('form', { name: `Edit details for ${renamed}`, exact: true }).count(), 0);
  assert.equal(await inlineRow.getByRole('button', { name: 'Edit details', exact: true }).evaluate(el => el === document.activeElement), true);
  const more = inlineRow.getByLabel(`More actions for ${renamed}`, { exact: true });
  await more.click(); await page.keyboard.press('Escape');
  assert.equal(await inlineRow.getByRole('button', { name: 'Delete variant', exact: true }).isVisible(), false);
  await search.fill('no matching catalog variant');
  await page.getByText('No matching variants', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await search.fill('Finance Department');
  await page.getByRole('article', { name: renamed, exact: true }).waitFor();
  await search.fill(renamed);
  await page.getByRole('combobox', { name: 'Filter variants by status' }).selectOption('DRAFT');
  await inlineRow.waitFor();
  await page.getByRole('combobox', { name: 'Filter variants by status' }).selectOption('PUBLISHED');
  await page.getByText('No matching variants', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `catalog overflow at ${width}`);
    if (width === 390 || width === 1440) await page.screenshot({ path: `/tmp/passport-catalog-${width}.png`, fullPage: true });
    await inlineRow.getByRole('button', { name: 'Edit details', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `inline form overflow at ${width}`);
    await page.getByRole('form', { name: `Edit details for ${renamed}`, exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click();
  }
  console.log('PASS: search, department matching, status filtering, empty state, direct builder link, Escape/focus restoration and responsive inline forms at 320–1440px');
  stage = 'delete variant';
  page.once('dialog', modal => modal.accept());
  await page.getByRole('article', { name: renamed, exact: true }).getByLabel(`More actions for ${renamed}`, { exact: true }).click();
  await page.getByRole('article', { name: renamed, exact: true }).getByRole('button', { name: 'Delete variant', exact: true }).click();
  await page.getByRole('heading', { name: renamed, exact: true }).waitFor({ state: 'detached' });
  assert.equal((await prisma.trainingPlan.findUniqueOrThrow({ where: { id: variant.planId } })).status, 'ARCHIVED');
  assert.equal(await prisma.traineeProgress.count({ where: { traineeId: trainee.id } }), 21);
  assert.equal((await prisma.traineeProgress.findUniqueOrThrow({ where: { id: stamp.id } })).verificationHash, stamp.verificationHash);
  console.log('PASS: customized active-instance promotion, reusable draft without progress, mobile catalog and safe variant deletion');
  await browser.close(); browser = undefined;
  stage = 'explicit individual conversion';
  legacy = await prisma.trainee.create({ data: { traineeCode: `CATL-${suffix}`, fullName: 'Legacy Browser Fixture', email: `catl-${suffix}@example.invalid`, restaurantBrand: 'Test', branchLocation: 'Test', cohortBatch: 'Test', hireDate: new Date() } });
  const masterVersion = await prisma.planVersion.findFirstOrThrow({ where: { planId: 'plan-tbg-corporate-foundation-l1', status: 'PUBLISHED' }, orderBy: { versionNumber: 'desc' }, include: { nodes: true } });
  await prisma.traineePlanAssignment.create({ data: { traineeId: legacy.id, planVersionId: masterVersion.id, assignedById: trainer.id } });
  await prisma.traineeProgress.createMany({ data: masterVersion.nodes.map(node => ({ traineeId: legacy.id, planNodeId: node.id, status: 'IN_PROGRESS' })) });
  const old = await prisma.traineeProgress.findFirstOrThrow({ where: { traineeId: legacy.id } });
  const awarded = await prisma.traineeProgress.update({ where: { id: old.id }, data: verificationData(legacy.id, old.planNodeId, trainer.id, new Date(), 'Legacy fixture approval') });
  await freshPage(`/trainer/trainees/${legacy.id}`, true);
  await page.getByRole('region', { name: 'Existing shared path', exact: true }).waitFor();
  assert.equal((await prisma.traineePlanAssignment.findFirstOrThrow({ where: { traineeId: legacy.id, status: 'ACTIVE' } })).planVersionId, masterVersion.id);
  await page.getByRole('button', { name: 'Create Individual Instance', exact: true }).click();
  await page.getByRole('region', { name: 'Active path instance', exact: true }).waitFor({ timeout: 45000 });
  assert.equal((await prisma.traineeProgress.findUniqueOrThrow({ where: { id: awarded.id } })).verificationHash, awarded.verificationHash);
  assert.equal(await prisma.learningPath.count({ where: { traineeId: legacy.id, type: 'INSTANCE' } }), 1);
  console.log('PASS: viewing a legacy profile leaves assignments unchanged; explicit single-trainee conversion preserves progress IDs and original stamp hash');

})().catch(error => { console.error(`Catalog browser check failed at ${stage}: ${String(error.message || error.name).replace(/https?:\/\/[^\s]+/g, "[URL]").slice(0, 2200)}`); process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  const paths = trainer ? await prisma.learningPath.findMany({ where: { plan: { createdById: trainer.id } } }) : [];
  const custom = trainer ? await prisma.planNode.findMany({ where: { isCustom: true, planVersion: { plan: { createdById: trainer.id } } }, select: { code: true } }) : [];
  if (trainee) await prisma.trainee.delete({ where: { id: trainee.id } });
  if (legacy) await prisma.trainee.delete({ where: { id: legacy.id } });
  await prisma.trainingPlan.deleteMany({ where: { id: { in: paths.filter(path => path.type === 'INSTANCE').map(path => path.planId) } } });
  await prisma.trainingPlan.deleteMany({ where: { id: { in: paths.filter(path => path.type === 'VARIANT').map(path => path.planId) } } });
  if (custom.length) await prisma.milestoneDefinition.deleteMany({ where: { code: { in: custom.map(node => node.code) } } });
  if (trainer) await prisma.adminUser.delete({ where: { id: trainer.id } });
  await prisma.$disconnect();
});
